"""Build the browser copy of E's voice-guide fast path (worker/recyclone_worker/guide_identify.py) for /camera.

Writes, from the worker's own code so the two never drift:
  public/models/yolo11n-pose.onnx   pose model (ultralytics export, 640x640)
  public/models/guide.json          CLIP text embeddings for guide_prompts() + BACKGROUND, the bin table, constants
  lib/guide/__fixtures__/parity.json  the worker's outputs on real hand crops, for the TypeScript tests

The CLIP image model is not copied: browsers load it from Hugging Face (Xenova/clip-vit-base-patch32, pinned below).
Its fp16 export agreed with the worker's CLIP on the bin for 224/228 hand crops from the dev clips (17 Oct).

Run with the worker's environment, from apps/web:
    ../../worker/.venv/bin/python scripts/build_guide_model.py [--clips ~/Downloads/IMG_9096.MOV ...]
"""

import argparse
import json
import shutil
from pathlib import Path

import numpy as np

from recyclone_worker import guide_identify as gi
from recyclone_worker import guide_message as gm
from recyclone_worker.items import BACKGROUND, Clip, Scorer, hand_box, weight

WEB = Path(__file__).resolve().parents[1]
CLIP_REPO, CLIP_REVISION = "Xenova/clip-vit-base-patch32", "d15189d7028b43f1d3e65039190477f6af591c2a"


def rounded(a: np.ndarray, digits: int = 5) -> list:
    return np.round(a.astype(np.float64), digits).tolist()


def export_pose(out: Path) -> None:
    from ultralytics import YOLO

    exported = Path(YOLO(str(weight("yolo11n-pose.pt"))).export(format="onnx", imgsz=640, opset=17, simplify=True, dynamic=False))
    shutil.move(exported, out)


def hand_crops(clips: list[Path], pose_weights: Path, every: int = 6, limit: int = 40):
    """(crop, keypoints, frame size) of hands in the dev clips, for the parity fixture."""
    import cv2
    from ultralytics import YOLO

    pose = YOLO(str(pose_weights))
    found = []
    for clip in clips:
        cap = cv2.VideoCapture(str(clip))
        i = 0
        while len(found) < limit * (clips.index(clip) + 1) // len(clips):
            ok, f = cap.read()
            if not ok:
                break
            if i % every == 0:
                r = pose.predict(f, imgsz=640, verbose=False, conf=0.3)[0]
                if r.keypoints is not None and len(r.keypoints):
                    for kp in r.keypoints.data.cpu().numpy():
                        for side in ("L", "R"):
                            b = hand_box(kp, side, f.shape[1], f.shape[0])
                            if b:
                                x0, y0, x1, y1 = (int(v) for v in b)
                                found.append((f[y0:y1, x0:x1], kp, (f.shape[1], f.shape[0]), side, b))
            i += 1
    return found


def watcher_case(scorer: Scorer, table: dict, embs: np.ndarray) -> dict:
    """The worker's ItemWatcher on a fixed sequence of hand embeddings (one hand, 10 observations a second)."""
    stream = iter(embs)
    watcher = gi.ItemWatcher(lambda crops: np.stack([next(stream) for _ in crops]), scorer, table, namer=None)
    kp = np.zeros((17, 3), np.float32)
    kp[7], kp[9] = (300, 300, 0.9), (300, 400, 0.9)  # left elbow above left wrist: one hand crop per observation
    frame = np.zeros((720, 1280, 3), np.uint8)
    steps = []
    for i in range(len(embs)):
        t = round(0.1 * i, 3)
        watcher.observe(1, t, frame, kp)
        ans = watcher.answer(1, t)
        steps.append({"t": t, "holding": watcher.holding(1, t), "answer": ans[0] if ans else None})
    return {"embeddings": rounded(embs), "steps": steps}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--clips", nargs="*", default=[], help="dev clips for the parity fixture (skipped if none)")
    args = ap.parse_args()

    models = WEB / "public/models"
    models.mkdir(parents=True, exist_ok=True)
    export_pose(models / "yolo11n-pose.onnx")

    clip = Clip(weight("clip/ViT-B-32.pt"))
    prompts = gi.guide_prompts()
    scorer = Scorer(clip, prompts)
    table = gm.load_bin_table(gm.WORKER_RULES / "cambridge-ma-2022.bins.json")
    data = {
        "source": "generated by apps/web/scripts/build_guide_model.py from worker/recyclone_worker (guide_identify, items, "
                  "guide_message) and worker/rules/cambridge-ma-2022.bins.json; do not edit by hand",
        "clip": {"repo": CLIP_REPO, "revision": CLIP_REVISION, "webgpu": "onnx/vision_model_fp16.onnx",
                 "wasm": "onnx/vision_model_quantized.onnx"},
        "cats": scorer.cats,
        "prompt_owner": scorer.item_owner.tolist(),
        "item_text": rounded(scorer.item_text),
        "bg_text": rounded(scorer.bg_text),
        "background": BACKGROUND,
        "table": {k: {"bin": v["bin"], "name": v["name"]} for k, v in table.items()},
        "constants": {"item_p": gi.ITEM_P, "known_p": gi.KNOWN_P, "min_votes": gi.MIN_VOTES,
                      "hold_window_s": gi.HOLD_WINDOW_S, "observe_every_s": gi.OBSERVE_EVERY_S,
                      "max_words": gm.MAX_WORDS, "logit_scale": 100},
    }
    (models / "guide.json").write_text(json.dumps(data, separators=(",", ":")))
    print(f"wrote {models / 'guide.json'} ({len(scorer.cats)} categories, {len(scorer.item_owner)} prompts)")

    if not args.clips:
        return
    crops = hand_crops([Path(c).expanduser() for c in args.clips], weight("yolo11n-pose.pt"))
    embs = clip.images([c for c, *_ in crops])
    p_item, p_cat = scorer(embs)
    fixture = {
        "score": [{"embedding": rounded(e), "p_item": float(pi), "p_cat": rounded(pc, 6)}
                  for e, pi, pc in zip(embs[:12], p_item[:12], p_cat[:12])],
        "hand_box": [{"kp": rounded(kp, 3), "size": list(size), "side": side, "box": rounded(np.array(b), 3)}
                     for _, kp, size, side, b in crops[:12]],
        # mixed: the dev clips in order (votes split, so no catalog answer); steady: the crop CLIP is surest about,
        # seen 8 times (answered from the table after MIN_VOTES).
        "watcher": {"mixed": watcher_case(scorer, table, embs),
                    "steady": watcher_case(scorer, table, np.repeat(embs[[int(np.argmax(p_cat.max(1) * p_item))]], 8, 0))},
        "catalog_messages": {k: gm.from_catalog(k, table) for k in table},
        "default_trash": gm.default_trash(None),
    }
    out = WEB / "lib/guide/__fixtures__/parity.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(fixture, separators=(",", ":")))
    print(f"wrote {out} ({len(crops)} hand crops)")


if __name__ == "__main__":
    main()
